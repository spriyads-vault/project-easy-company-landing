/**
 * Homepage v8 (dark), served at "/" when NEXT_PUBLIC_FF_HOMEPAGE_V8 is on (next.config.ts). Source: Claude Design
 * "Crado_Landing_v8.dc.html". The share images are generated by src/app/(home)/opengraph-image.tsx and
 * twitter-image.tsx.
 */
export const metadata: Metadata = {
  title: { absolute: V8_TITLE },
  description: V8_DESCRIPTION,
  robots: { index: true, follow: true, "max-image-preview": "large" },
  openGraph: { type: "website", siteName: SITE_NAME, title: V8_TITLE, description: V8_DESCRIPTION },
  twitter: { card: "summary_large_image", title: V8_TITLE, description: V8_DESCRIPTION },
};

export const viewport: Viewport = {
  colorScheme: "dark",
  themeColor: "#0D0D0F",
};

/**
 * Runs before first paint: turns motion on (html[data-v8-motion]) unless the visitor prefers reduced motion, so the
 * animated elements start in their first frame rather than flashing in. If the page's script never starts, motion is
 * switched off again after 4 seconds so nothing stays hidden.
 */
const MOTION_SCRIPT = `(function(){var d=document.documentElement;if(window.matchMedia&&matchMedia("(prefers-reduced-motion: reduce)").matches)return;d.setAttribute("data-v8-motion","");setTimeout(function(){if(!d.hasAttribute("data-v8-ready"))d.removeAttribute("data-v8-motion")},4000)})();`;

export default function HomePage() {
  return (
    <div data-home-v8 className={`${V8_FONT_VARIABLES} overflow-x-clip bg-v8-page font-v8-sans text-[18px] leading-[29px] text-v8-white antialiased [font-variant-numeric:normal]`}>
      <script dangerouslySetInnerHTML={{ __html: MOTION_SCRIPT }} />
      {/* React hoists these into <head>. Next normalises a "/" canonical to the bare origin, so it is written here. */}
      <link rel="canonical" href={HOME_URL} />
      <meta property="og:url" content={HOME_URL} />
      {V8_JSON_LD.map((d) => (
        <JsonLd key={d["@type"]} data={d} />
      ))}
      <SkipLink target="main" />
      <SiteHeader />
      <main id="main">
        <Hero />
        <LegacyAnchors section={IDS.productGraph} />
        <Gap />
        <LegacyAnchors section={IDS.continuity} />
        <Continuity />
        <LegacyAnchors section={IDS.workflow} />
        <Workflows />
        <LegacyAnchors section={IDS.engine} />
        <Method />
        <LegacyAnchors section={IDS.capabilities} />
        <Capabilities />
        <Faq />
        <LegacyAnchors section={IDS.getStarted} />
        <Start />
      </main>
      <Footer />
      <Motion />
    </div>
  );
}
